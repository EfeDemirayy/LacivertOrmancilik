import { promises as fs } from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const SOURCE_FILE = path.join(ROOT, "src", "generated", "pages.ts");
const OUTPUT_DIR = path.join(ROOT, "public", "page-data", "pages");
const MANIFEST_FILE = path.join(ROOT, "src", "generated", "pageManifest.ts");

const readJsonAssignment = (source, startToken, endToken) => {
  const start = source.indexOf(startToken);
  if (start === -1) {
    throw new Error(`Token not found: ${startToken}`);
  }

  const from = start + startToken.length;
  const end = source.indexOf(endToken, from);
  if (end === -1) {
    throw new Error(`End token not found for: ${startToken}`);
  }

  const jsonText = source.slice(from, end).trim();
  return JSON.parse(jsonText);
};

const ensureCleanDir = async (directory) => {
  await fs.rm(directory, { recursive: true, force: true });
  await fs.mkdir(directory, { recursive: true });
};

const normalizeAlias = (value) => {
  if (!value) return "/";
  let normalized = String(value).trim();
  if (!normalized.startsWith("/")) normalized = `/${normalized}`;
  normalized = normalized.replace(/\/+/g, "/");
  if (normalized.length > 1 && normalized.endsWith("/")) normalized = normalized.slice(0, -1);
  return normalized;
};

const main = async () => {
  const source = await fs.readFile(SOURCE_FILE, "utf8");

  const pages = readJsonAssignment(
    source,
    "export const GENERATED_PAGES: GeneratedPage[] =",
    ";\n\nexport const PAGE_ALIAS_TO_INDEX"
  );

  const pageAliasToIndex = readJsonAssignment(
    source,
    "export const PAGE_ALIAS_TO_INDEX: Record<string, number> =",
    ";"
  );

  await ensureCleanDir(OUTPUT_DIR);

  const manifest = [];

  for (let i = 0; i < pages.length; i += 1) {
    const page = pages[i];
    const id = i;

    const output = {
      id,
      route: page.route,
      source: page.source,
      html: page.html,
      aliases: page.aliases,
    };

    await fs.writeFile(
      path.join(OUTPUT_DIR, `${id}.json`),
      JSON.stringify(output),
      "utf8"
    );

    manifest.push({
      id,
      route: page.route,
      source: page.source,
      aliases: page.aliases,
    });
  }

  const aliasToPageId = {};

  Object.entries(pageAliasToIndex).forEach(([alias, index]) => {
    const pageId = Number(index);
    if (!Number.isFinite(pageId)) return;

    const canonicalAlias = normalizeAlias(alias.toLowerCase());
    if (!(canonicalAlias in aliasToPageId)) aliasToPageId[canonicalAlias] = pageId;
  });

  manifest.forEach((entry) => {
    entry.aliases.forEach((alias) => {
      const canonicalAlias = normalizeAlias(alias.toLowerCase());
      if (!(canonicalAlias in aliasToPageId)) aliasToPageId[canonicalAlias] = entry.id;
    });
  });

  const manifestSource = `/* eslint-disable */\n/* This file is auto-generated by scripts/build-page-data.mjs. */\n\nexport type PageManifestEntry = {\n  id: number;\n  route: string;\n  source: string;\n  aliases: string[];\n};\n\nexport const PAGE_MANIFEST: PageManifestEntry[] = ${JSON.stringify(manifest, null, 2)};\n\nexport const ALIAS_TO_PAGE_ID: Record<string, number> = ${JSON.stringify(aliasToPageId, null, 2)};\n`;

  await fs.mkdir(path.dirname(MANIFEST_FILE), { recursive: true });
  await fs.writeFile(MANIFEST_FILE, manifestSource, "utf8");

  console.log(`Prepared ${manifest.length} lazy pages.`);
};

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
